import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

/**
 * Loads key=value pairs from a local .env file if present (without overriding process.env).
 * @param {string} envPath
 */
function loadDotEnvIfExists(envPath) {
  if (!fs.existsSync(envPath)) return;
  const content = fs.readFileSync(envPath, "utf8");
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eqIndex = line.indexOf("=");
    if (eqIndex <= 0) continue;
    const key = line.slice(0, eqIndex).trim();
    let value = line.slice(eqIndex + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) {
      process.env[key] = value;
    }
  }
}

loadDotEnvIfExists(path.join(rootDir, ".env"));

const supabaseUrl = (process.env.SUPABASE_URL || "").trim();
const supabaseAnonKey = (process.env.SUPABASE_ANON_KEY || "").trim();

if (!supabaseUrl || !supabaseAnonKey) {
  console.warn(
    "[build:config] Warning: SUPABASE_URL or SUPABASE_ANON_KEY is not set. " +
      "Writing placeholder js/config.js; configure environment variables in Vercel or .env."
  );
}

const outputContent = `// Auto-generated by scripts/build-config.js — do not commit secrets.
export const APP_CONFIG = Object.freeze({
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  appName: "Vehicle Logbook",
  currency: "IDR",
  locale: "id-ID"
});
`;

const targetPath = path.join(rootDir, "js", "config.js");
fs.mkdirSync(path.dirname(targetPath), { recursive: true });
fs.writeFileSync(targetPath, outputContent, "utf8");
console.log("[build:config] Generated js/config.js successfully.");
