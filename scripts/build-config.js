import fs from "node:fs";
import path from "node:path";

const rootDir = process.cwd();
const outputDir = path.join(rootDir, "js", "config");
const targetFile = path.join(outputDir, "env.js");

const supabaseUrl =
  process.env.SUPABASE_URL ||
  process.env.VITE_SUPABASE_URL ||
  process.env.NEXT_PUBLIC_SUPABASE_URL ||
  "";

const supabaseAnonKey =
  process.env.SUPABASE_ANON_KEY ||
  process.env.VITE_SUPABASE_ANON_KEY ||
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
  "";

fs.mkdirSync(outputDir, { recursive: true });

const content = `// Auto-generated by scripts/build-config.js — do not commit real secrets
export const SUPABASE_CONFIG = Object.freeze({
  url: ${JSON.stringify(supabaseUrl)},
  anonKey: ${JSON.stringify(supabaseAnonKey)},
});
`;

fs.writeFileSync(targetFile, content, "utf8");
console.log("Generated js/config/env.js successfully.");
